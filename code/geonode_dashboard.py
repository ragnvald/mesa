"""
GeoNode dashboards for MESA.

Turns a list of declarative widget specs (from a publishing recipe in
geonode_export) into a MapStore dashboard and saves it as a GeoNode GeoApp.

Widget specs:
  {"type": "text",    "title", "text"}                          HTML
  {"type": "counter", "title", "field", "op"}                   op: sum|count|avg|min|max
  {"type": "chart",   "title", "chart": "bar"|"pie", "group_by", "field", "op", "colors"?}
  {"type": "table",   "title", "columns"}
  {"type": "map"}     the published dataset, one layer per style
colors maps a group_by value (typed as in the data) to a hex colour.

API used:
  POST   /api/v2/geoapps/              create (resource_type "dashboard", data in the body)
  GET    /api/v2/geoapps/?filter{...}  find earlier MESA dashboards of the same title
  DELETE /api/v2/resources/<pk>/       remove them
  GET    /geoserver/ows DescribeFeatureType   geometry attribute name (geomProp)
Charts and counters aggregate server-side through GeoServer WPS gs:Aggregate.
Format follows geonode-mapstore-client 5.0.x / MapStore 2025.02 (charts[].traces[]).
"""

from __future__ import annotations

import uuid
from typing import Callable, Optional

import requests

DASHBOARD_MARKER = "Generated by MESA"   # in the abstract; marks dashboards MESA may replace

_OPS = {"sum": "Sum", "count": "Count", "avg": "Average", "min": "Min", "max": "Max"}
_COLS = 6            # MapStore dashboard grid, md breakpoint
_DEFAULT_COLOR = "#0888A1"


def _uid() -> str:
    return str(uuid.uuid4())


def geometry_attribute(base_url: str, username: str, password: str, alternate: str) -> str:
    """Name of the dataset's geometry attribute, which widgets need to filter by
    the map extent. Falls back to "geom", what the GeoNode importer usually makes."""
    try:
        r = requests.get(
            f"{base_url.rstrip('/')}/geoserver/ows",
            params={"service": "WFS", "version": "2.0.0", "request": "DescribeFeatureType",
                    "typeName": alternate, "outputFormat": "application/json"},
            auth=(username, password), timeout=20)
        if r.status_code == 200:
            for prop in (r.json().get("featureTypes") or [{}])[0].get("properties", []):
                if str(prop.get("type", "")).startswith("gml:"):
                    return prop["name"]
    except Exception:
        pass
    return "geom"


def _layer_obj(ows: str, alternate: str, title: str) -> dict:
    return {"type": "wms", "url": ows, "name": alternate, "title": title,
            "search": {"type": "wfs", "url": ows}, "visibility": True}


def _connection(map_widget_id: Optional[str], map_id: Optional[str]) -> dict:
    """mapSync + dependenciesMap so a widget follows the map widget's extent."""
    if not map_widget_id:
        return {"mapSync": False}
    w, m = map_widget_id, map_id
    return {"mapSync": True, "dependenciesMap": {
        "viewport": f"widgets[{w}].maps[{m}].viewport",
        "layers": f"widgets[{w}].maps[{m}].layers",
        "groups": f"widgets[{w}].maps[{m}].groups",
        "mapSync": f"widgets[{w}].mapSync",
        "dependenciesMap": f"widgets[{w}].dependenciesMap",
    }}


def _classification(colors: dict) -> dict:
    classes = [{"id": _uid(), "title": str(v), "color": c, "value": v, "unique": v}
               for v, c in colors.items() if c]
    return {"msMode": "classification", "msClassification": {
        "method": "uniqueInterval", "intervals": max(1, len(classes)), "reverse": False,
        "ramp": "viridis", "defaultColor": _DEFAULT_COLOR, "defaultLabel": "Other",
        "classes": classes}}


def _chart_widget(spec: dict, layer: dict, geom: str, conn: dict) -> dict:
    chart_id, trace_id = _uid(), f"trace-{_uid()}"
    kind = spec.get("chart", "bar")
    style = (_classification(spec["colors"]) if spec.get("colors") else
             {"msMode": "simple", "line": {"color": "rgb(0, 0, 0)", "width": 0},
              "marker": {"color": _DEFAULT_COLOR}})
    trace = {
        "id": trace_id, "type": kind, "name": spec["title"],
        "options": {"groupByAttributes": spec["group_by"],
                    "aggregationAttribute": spec["field"],
                    "aggregateFunction": _OPS[spec.get("op", "sum")]},
        "style": style, "geomProp": geom, "layer": layer,
    }
    if kind == "pie":
        trace["includeLegendPercent"] = True
    # No widget-level "layer": MapStore's convertDependenciesMappingForCompatibility
    # treats a chart widget with one as legacy and replaces its traces with empty ones.
    return {
        "widgetType": "chart", "title": spec["title"],
        "selectedChartId": chart_id, "selectedTraceId": trace_id,
        "charts": [{"chartId": chart_id, "name": spec["title"], "legend": kind == "pie",
                    "cartesian": True, "barChartType": "group",
                    "xAxisOpts": [{"id": 0}], "yAxisOpts": [{"id": 0, "hide": False}],
                    "traces": [trace]}],
        **conn,
    }


def _counter_widget(spec: dict, layer: dict, geom: str, conn: dict) -> dict:
    return {
        "widgetType": "counter", "title": spec["title"], "layer": layer, "url": layer["url"],
        "geomProp": geom, "legend": False, "cartesian": True, "yAxis": True,
        "options": {"propertyName": [spec["field"]], "aggregationAttribute": spec["field"],
                    "aggregateFunction": _OPS[spec.get("op", "sum")]},
        "counterOpts": {"format": ",.0f"},
        **conn,
    }


def _table_widget(spec: dict, layer: dict, geom: str, conn: dict) -> dict:
    return {
        "widgetType": "table", "title": spec["title"], "layer": layer, "url": layer["url"],
        "geomProp": geom, "legend": False, "cartesian": True, "yAxis": True,
        "options": {"propertyName": list(spec["columns"])},
        **conn,
    }


def _layout(widgets: list[dict]) -> None:
    """Place widgets on the 6-column grid (row = 150 px): text and counters stack in
    a 2-wide column beside the map, charts two per row below, tables full width."""
    side = [w for w in widgets if w["widgetType"] in ("text", "counter")]
    maps = [w for w in widgets if w["widgetType"] == "map"]
    charts = [w for w in widgets if w["widgetType"] == "chart"]
    tables = [w for w in widgets if w["widgetType"] == "table"]

    y = 0
    for w in side:
        h = 2 if w["widgetType"] == "text" else 1
        w["dataGrid"] = {"x": 0, "y": y, "w": 2, "h": h}
        y += h
    top_h = max(y, 3)
    for w in maps:
        w["dataGrid"] = {"x": 2 if side else 0, "y": 0, "w": 4 if side else _COLS, "h": top_h}
    y = top_h if (side or maps) else 0
    for i, w in enumerate(charts):
        w["dataGrid"] = {"x": (i % 2) * 3, "y": y + (i // 2) * 2, "w": 3, "h": 2}
    y += ((len(charts) + 1) // 2) * 2
    for w in tables:
        w["dataGrid"] = {"x": 0, "y": y, "w": _COLS, "h": 3}
        y += 3


def build_dashboard_data(
    base_url: str,
    alternate: str,
    dataset_pk: int,
    styles: list[tuple[str, str]],
    bbox: Optional[list[float]],
    specs: list[dict],
    geom: str = "geom",
    dataset_title: Optional[str] = None,
) -> dict:
    """MapStore dashboard `data` ({widgets, layouts}) for one published dataset."""
    from geonode_export import build_group_map_config

    base = base_url.rstrip("/")
    ows = f"{base}/geoserver/ows"
    layer = _layer_obj(ows, alternate, dataset_title or alternate.split(":")[-1])

    map_widget_id = map_id = None
    if styles and any(s.get("type") == "map" for s in specs):
        map_widget_id, map_id = _uid(), _uid()
    conn = _connection(map_widget_id, map_id)

    widgets: list[dict] = []
    for spec in specs:
        t = spec.get("type")
        if t == "text":
            w = {"widgetType": "text", "title": spec.get("title", ""), "text": spec["text"]}
        elif t == "counter":
            w = _counter_widget(spec, layer, geom, conn)
        elif t == "chart":
            w = _chart_widget(spec, layer, geom, conn)
        elif t == "table":
            w = _table_widget(spec, layer, geom, conn)
        elif t == "map" and map_widget_id:
            cfg, _ = build_group_map_config(base, alternate, dataset_pk, styles, bbox)
            ms = dict(cfg["map"], mapId=map_id)
            ms["layers"] = [dict(l, search={"type": "wfs", "url": ows}) if l.get("type") == "wms" else l
                            for l in ms["layers"]]
            w = {"id": map_widget_id, "widgetType": "map", "title": "Map", "mapSync": False,
                 "selectedMapId": map_id, "maps": [ms]}
        else:
            continue
        w.setdefault("id", _uid())
        widgets.append(w)

    _layout(widgets)
    layouts = {"md": [dict(w["dataGrid"], i=w["id"], moved=False, static=False) for w in widgets]}
    return {"widgets": widgets, "layouts": layouts, "catalogs": None}


def _delete_generated_dashboards(base: str, auth, title: str, log: Callable[[str], None]) -> None:
    """Remove earlier MESA-generated dashboards with this exact title (marker in abstract)."""
    try:
        r = requests.get(f"{base}/api/v2/geoapps/",
                         params={"filter{resource_type}": "dashboard", "filter{title}": title,
                                 "page_size": 50},
                         auth=auth, timeout=20)
        apps = r.json().get("geoapps", []) if r.status_code == 200 else []
    except Exception:
        return
    for a in apps:
        abstract = a.get("raw_abstract") or a.get("abstract") or ""
        if a.get("title") != title or DASHBOARD_MARKER not in abstract:
            continue
        try:
            d = requests.delete(f"{base}/api/v2/resources/{a['pk']}/", auth=auth, timeout=30)
            log(f"  Dashboard: removed previous '{title}' (pk={a['pk']}, HTTP {d.status_code}).")
        except Exception as exc:
            log(f"  Dashboard: could not remove previous pk={a.get('pk')}: {exc}")


def create_dashboard(
    base_url: str,
    username: str,
    password: str,
    title: str,
    alternate: str,
    dataset_pk: int,
    styles: list[tuple[str, str]],
    bbox: Optional[list[float]],
    specs: list[dict],
    log: Callable[[str], None],
) -> Optional[str]:
    """Create (replacing an earlier MESA one of the same title) a GeoNode dashboard.
    Returns its catalogue URL, or None on failure."""
    base = base_url.rstrip("/")
    auth = (username, password)
    geom = geometry_attribute(base, username, password, alternate)
    data = build_dashboard_data(base, alternate, dataset_pk, styles, bbox, specs, geom=geom)
    _delete_generated_dashboards(base, auth, title, log)

    body = {
        # name must be unique across GeoApps; the GeoNode client appends a uuid too.
        "name": f"{title} {uuid.uuid4()}",
        "owner": username,
        "resource_type": "dashboard",
        "title": title,
        "abstract": f"MESA statistics for {alternate.split(':')[-1]}. {DASHBOARD_MARKER}.",
        "data": data,
    }
    try:
        r = requests.post(f"{base}/api/v2/geoapps/", auth=auth, json=body, timeout=60)
    except Exception as exc:
        log(f"  Dashboard: POST /api/v2/geoapps/ failed ({exc}).")
        return None
    if r.status_code not in (200, 201):
        log(f"  Dashboard: creation failed (HTTP {r.status_code}: {r.text[:200]}).")
        return None
    try:
        pk = r.json().get("geoapp", {}).get("pk")
    except Exception:
        pk = None
    if not pk:
        log("  Dashboard: created but could not read pk from response.")
        return None
    log(f"  Dashboard '{title}' (pk={pk}) with {len(data['widgets'])} widget(s).")
    return f"{base}/catalogue/#/dashboard/{pk}"
