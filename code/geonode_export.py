def _delete_generated_maps(base: str, auth, title: str, log: Callable[[str], None]) -> None:
    """Remove earlier MESA-generated maps with this exact title (marker in abstract)."""
    try:
        r = requests.get(f"{base}/api/v2/maps/", params={"filter{title}": title, "page_size": 50},
                         auth=auth, timeout=20)
        maps = r.json().get("maps", []) if r.status_code == 200 else []
    except Exception:
        return
    for m in maps:
        if m.get("title") != title or _MAP_MARKER not in (m.get("raw_abstract") or m.get("abstract") or ""):
            continue
        try:
            d = requests.delete(f"{base}/api/v2/resources/{m['pk']}/", auth=auth, timeout=30)
            log(f"  Map: removed previous '{title}' (pk={m['pk']}, HTTP {d.status_code}).")
        except Exception as exc:
            log(f"  Map: could not remove previous map pk={m.get('pk')}: {exc}")


def create_group_map(
    base_url: str,
    username: str,
    password: str,
    title: str,
    alternate: str,
    dataset_pk: int,
    styles: list[tuple[str, str]],
    bbox: Optional[list[float]],
    log: Callable[[str], None],
) -> Optional[str]:
    """Create (replacing an earlier MESA one) a GeoNode map with one layer per style
    of a single dataset. Returns the map catalogue URL, or None on failure."""
    base = base_url.rstrip("/")
    auth = (username, password)
    _delete_generated_maps(base, auth, title, log)

    abstract = (f"MESA results for one geocode group. Layers: "
                f"{', '.join(t for _, t in styles)}. {_MAP_MARKER}.")
    try:
        r = requests.post(f"{base}/api/v2/maps/", auth=auth,
                          json={"title": title, "abstract": abstract}, timeout=30)
    except Exception as exc:
        log(f"  Map: POST /api/v2/maps/ failed ({exc}).")
        return None
    if r.status_code not in (200, 201):
        log(f"  Map: creation failed (HTTP {r.status_code}: {r.text[:200]}).")
        return None
    body = r.json()
    map_pk = body.get("map", body).get("pk")
    if not map_pk:
        log("  Map: created but could not read pk from response.")
        return None

    data, maplayers = build_group_map_config(base, alternate, dataset_pk, styles, bbox)
    try:
        r2 = requests.patch(f"{base}/api/v2/maps/{map_pk}/", auth=auth,
                            json={"data": data, "maplayers": maplayers}, timeout=60)
        ok = r2.status_code in (200, 201, 204)
        err = "" if ok else f"HTTP {r2.status_code}: {r2.text[:160]}"
    except Exception as exc:
        ok, err = False, str(exc)
    if not ok:
        # An empty map in the catalogue looks published but shows nothing; remove it.
        log(f"  Map: could not add layers ({err}); removing the empty map.")
        try:
            requests.delete(f"{base}/api/v2/resources/{map_pk}/", auth=auth, timeout=30)
        except Exception:
            pass
        return None
    log(f"  Map '{title}' (pk={map_pk}) with {len(styles)} layer(s).")
    return f"{base}/catalogue/#/map/{map_pk}"


