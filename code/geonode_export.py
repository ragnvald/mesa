def _map_center_zoom(bbox: Optional[list[float]]) -> tuple[dict, int]:
    """MapStore centre (EPSG:4326) and a zoom that fits bbox [minx, miny, maxx, maxy]."""
    import math
    if not bbox or len(bbox) != 4:
        return {"x": 0.0, "y": 0.0, "crs": "EPSG:4326"}, 2
    minx, miny, maxx, maxy = (float(v) for v in bbox)
    span = max(maxx - minx, (maxy - miny) * 1.6, 1e-6)
    zoom = int(max(1, min(16, math.floor(math.log2(360.0 / span)) + 1)))
    return {"x": (minx + maxx) / 2.0, "y": (miny + maxy) / 2.0, "crs": "EPSG:4326"}, zoom


def build_group_map_config(
    base_url: str,
    alternate: str,
    dataset_pk: int,
    styles: list[tuple[str, str]],
    bbox: Optional[list[float]],
    visible_index: int = 0,
) -> tuple[dict, list[dict]]:
    """MapStore config (GeoNode map 'data') and maplayers for one dataset shown
    once per (style_name, title). Only styles[visible_index] starts visible, so
    the viewer switches between them like the MESA Overview radios."""
    base = base_url.rstrip("/")
    center, zoom = _map_center_zoom(bbox)
    layers: list[dict] = [{
        "id": "mapnik__0", "name": "mapnik", "type": "osm", "group": "background",
        "title": "OpenStreetMap", "source": "osm", "visibility": True,
        "extraParams": {"msId": "mapnik__0"},
    }]
    maplayers: list[dict] = []
    wms_bbox = None
    if bbox and len(bbox) == 4:
        wms_bbox = {"crs": "EPSG:4326", "bounds": {
            "minx": bbox[0], "miny": bbox[1], "maxx": bbox[2], "maxy": bbox[3]}}
    # MapStore draws the list bottom-up, so reverse to keep styles[0] on top of the TOC.
    for idx, (style_name, title) in reversed(list(enumerate(styles))):
        ms_id = f"{alternate.split(':')[-1]}__{idx}"
        style = f"geonode:{style_name}"
        visible = idx == visible_index
        lyr = {
            "id": ms_id, "type": "wms", "url": f"{base}/geoserver/ows",
            "name": alternate, "title": title, "style": style, "group": "Default",
            "format": "image/png", "opacity": 1, "visibility": visible,
            "singleTile": False, "extraParams": {"msId": ms_id},
        }
        if wms_bbox:
            lyr["bbox"] = wms_bbox
        layers.append(lyr)
        maplayers.append({
            "extra_params": {"msId": ms_id}, "current_style": style,
            # GeoNode resolves this relation by primary key; a dict here is a 500.
            "dataset": int(dataset_pk), "name": alternate,
            "visibility": visible, "opacity": 1,
        })
    data = {
        "version": 2,
        "map": {
            "projection": "EPSG:3857", "units": "m", "center": center, "zoom": zoom,
            "maxExtent": [-20037508.34, -20037508.34, 20037508.34, 20037508.34],
            "layers": layers,
            "groups": [{"id": "Default", "title": "Default", "expanded": True}],
            "backgrounds": [], "mapOptions": {},
        },
    }
    return data, maplayers


