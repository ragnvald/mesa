def build_sensitivity_sld(
    layer_name: str,
    field: str,
    colors: dict[str, str],
    descriptions: dict[str, str],
    opacity: float = _OVERLAY_OPACITY,
) -> str:
    """
    Build an SLD 1.0.0 document that styles *field* with the A-E colour palette.
    Rules are ordered E -> D -> C -> B -> A so highest sensitivity paints last.
    """

    def _rule(code: str, label: str, color: str, last: bool = False) -> str:
        fill_op = f"{opacity:.2f}"
        filter_block = (
            "      <ElseFilter/>"
            if last else
            f"      <ogc:Filter>\n"
            f"        <ogc:PropertyIsEqualTo>\n"
            f"          <ogc:PropertyName>{field}</ogc:PropertyName>\n"
            f"          <ogc:Literal>{code}</ogc:Literal>\n"
            f"        </ogc:PropertyIsEqualTo>\n"
            f"      </ogc:Filter>"
        )
        return (
            f"    <Rule>\n"
            f"      <Name>{code}</Name>\n"
            f"      <Title>{label}</Title>\n"
            f"{filter_block}\n"
            f"      <PolygonSymbolizer>\n"
            f"        <Fill>\n"
            f"          <CssParameter name=\"fill\">{color}</CssParameter>\n"
            f"          <CssParameter name=\"fill-opacity\">{fill_op}</CssParameter>\n"
            f"        </Fill>\n"
            f"        <Stroke>\n"
            f"          <CssParameter name=\"stroke\">{color}</CssParameter>\n"
            f"          <CssParameter name=\"stroke-width\">0.0</CssParameter>\n"
            f"          <CssParameter name=\"stroke-opacity\">0.0</CssParameter>\n"
            f"        </Stroke>\n"
            f"      </PolygonSymbolizer>\n"
            f"    </Rule>"
        )

    ordered = ["E", "D", "C", "B", "A"]
    rules_xml = "\n".join(
        _rule(
            code,
            f"{code} - {descriptions.get(code, code)}",
            colors.get(code, colors.get("UNKNOWN", "#BDBDBD")),
        )
        for code in ordered
    )
    rules_xml += "\n" + _rule(
        "UNKNOWN", "No data",
        colors.get("UNKNOWN", "#BDBDBD"),
        last=True,
    )

    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<StyledLayerDescriptor version="1.0.0"\n'
        '  xsi:schemaLocation="http://www.opengis.net/sld StyledLayerDescriptor.xsd"\n'
        '  xmlns="http://www.opengis.net/sld"\n'
        '  xmlns:ogc="http://www.opengis.net/ogc"\n'
        '  xmlns:xlink="http://www.w3.org/1999/xlink"\n'
        '  xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance">\n'
        f'  <NamedLayer>\n'
        f'    <Name>{layer_name}</Name>\n'
        f'    <UserStyle>\n'
        f'      <Title>MESA Sensitivity (maximum)</Title>\n'
        f'      <Abstract>A-E colour palette from MESA config.ini</Abstract>\n'
        f'      <FeatureTypeStyle>\n'
        f'{rules_xml}\n'
        f'      </FeatureTypeStyle>\n'
        f'    </UserStyle>\n'
        f'  </NamedLayer>\n'
        f'</StyledLayerDescriptor>\n'
    )


def _xml_escape(s: str) -> str:
    return (str(s).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))


def _fmt_num(v: float) -> str:
    return str(int(v)) if float(v).is_integer() else f"{float(v):.4g}"


def build_class_sld(
    style_name: str,
    style_title: str,
    field: str,
    classes: list[tuple[Optional[float], Optional[float], str, str]],
    opacity: float = _OVERLAY_OPACITY,
) -> str:
    """SLD 1.0.0 with one polygon rule per (lo, hi, colour, label) class:
    lo <= field < hi, with None meaning open-ended. Features outside every
    class (or NULL) are not drawn, as in the MESA map."""
    rules = []
    for lo, hi, color, label in classes:
        conds = []
        if lo is not None:
            conds.append(
                "<ogc:PropertyIsGreaterThanOrEqualTo>"
                f"<ogc:PropertyName>{field}</ogc:PropertyName><ogc:Literal>{lo}</ogc:Literal>"
                "</ogc:PropertyIsGreaterThanOrEqualTo>")
        if hi is not None:
            conds.append(
                "<ogc:PropertyIsLessThan>"
                f"<ogc:PropertyName>{field}</ogc:PropertyName><ogc:Literal>{hi}</ogc:Literal>"
                "</ogc:PropertyIsLessThan>")
        if not conds:
            conds.append(
                "<ogc:Not><ogc:PropertyIsNull>"
                f"<ogc:PropertyName>{field}</ogc:PropertyName>"
                "</ogc:PropertyIsNull></ogc:Not>")
        cond = conds[0] if len(conds) == 1 else "<ogc:And>" + "".join(conds) + "</ogc:And>"
        rules.append(
            "    <Rule>\n"
            f"      <Name>{_xml_escape(label)}</Name>\n"
            f"      <Title>{_xml_escape(label)}</Title>\n"
            f"      <ogc:Filter>{cond}</ogc:Filter>\n"
            "      <PolygonSymbolizer>\n"
            "        <Fill>\n"
            f"          <CssParameter name=\"fill\">{color}</CssParameter>\n"
            f"          <CssParameter name=\"fill-opacity\">{opacity:.2f}</CssParameter>\n"
            "        </Fill>\n"
            "      </PolygonSymbolizer>\n"
            "    </Rule>"
        )
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<StyledLayerDescriptor version="1.0.0"\n'
        '  xsi:schemaLocation="http://www.opengis.net/sld StyledLayerDescriptor.xsd"\n'
        '  xmlns="http://www.opengis.net/sld"\n'
        '  xmlns:ogc="http://www.opengis.net/ogc"\n'
        '  xmlns:xlink="http://www.w3.org/1999/xlink"\n'
        '  xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance">\n'
        '  <NamedLayer>\n'
        f'    <Name>{style_name}</Name>\n'
        '    <UserStyle>\n'
        f'      <Title>{_xml_escape(style_title)}</Title>\n'
        '      <FeatureTypeStyle>\n'
        + "\n".join(rules) + "\n"
        '      </FeatureTypeStyle>\n'
        '    </UserStyle>\n'
        '  </NamedLayer>\n'
        '</StyledLayerDescriptor>\n'
    )


